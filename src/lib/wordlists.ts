/** 累积词表:band N 的可用词 = band 1..N 的全部词(已小写、去重) */
export function cumulativeWordSet(band: Band): Set<string> {
  const set = new Set<string>();
  for (let b = 1 as Band; b <= band; b++) {
    for (const w of BANDS[b as Band]) set.add(w.toLowerCase());
  }
  return set;
}

